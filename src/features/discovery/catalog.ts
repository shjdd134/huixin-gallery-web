export type ExperienceMode = 'view' | 'cross' | 'make';
export const modeLabels: Record<ExperienceMode, string> = { view: '继续欣赏', cross: '换种媒介', make: '亲手尝试' };
export interface Activity { id: string; themeId: string; mode: ExperienceMode; title: string; minutes: string; materials: string; action: string; difference: string; review: string }
type Recipe = [title: string, minutes: string, materials: string, action: string, difference: string];
function theme(id: string, label: string, pattern: RegExp, recipes: Recipe[]) {
  return { id, label, pattern, activities: recipes.map((r, index): Activity => ({ id: `${id}-${index}`, themeId: id, mode: (['view', 'cross', 'make'] as const)[index], title: r[0], minutes: r[1], materials: r[2], action: r[3], difference: r[4], review: '哪一部分吸引你？遇到什么阻碍？隔几天还想再来一次吗？' })) };
}
